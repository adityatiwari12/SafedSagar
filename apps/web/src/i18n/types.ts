/** Dot-path keys into MessageTree, e.g. "hero.tagline" */
export type MessageKey = {
  [G in keyof MessageTree]: {
    [K in keyof MessageTree[G]]: `${G & string}.${K & string}`
  }[keyof MessageTree[G]]
}[keyof MessageTree]

